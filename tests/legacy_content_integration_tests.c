/* Production-loader integration tests for the legacy content adapter.
   Exercises the real CA_Startup / CA_StartupWithContent / CA_ResourceName /
   CA_Shutdown path against synthetic WL6 fixture directories.

   Usage: legacy_content_integration <original_dir> <renamed_dir> <scratch_dir>

   Scenarios:
     A. Default startup with original resource names succeeds and loads graphics.
     B. Renamed resources load through CA_StartupWithContent.
     C. Default startup rejects renamed-only directories; engine state stays safe.
     D. Invalid configurations fail safely with meaningful errors.
     E. Descriptor ownership: engine owns its copy, caller may mutate afterwards.
     F. Restart: original names, then renamed names, both load and shut down cleanly.

   Exit status is nonzero on the first failed assertion. No original commercial
   content is used; fixture data is generated by the Python wrapper. */
#include "ID_CA.h"
#include "ID_VL.h"
#include "legacy_content.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <sys/stat.h>
#include <sys/types.h>
#include <errno.h>
#include <stdint.h>
#include <stdarg.h>
#include "platform/data_file.h"

#define CHECK(cond) do { if (!(cond)) { fprintf(stderr, "FAIL %s:%d: %s (%s)\n", __FILE__, __LINE__, #cond, CA_Error()); return 1; } } while (0)
#define FAIL_MSG(msg) do { fprintf(stderr, "FAIL %s:%d: %s\n", __FILE__, __LINE__, msg); return 1; } while (0)

static int ScenarioOriginalStartupAndGraphics(const char *dir)
{
    legacy_content_t content;
    legacy_content_error_t err = LegacyContent_Init(&content, dir);
    if (err != LEGACY_CONTENT_OK) FAIL_MSG("LegacyContent_Init failed");
    fprintf(stderr, "scenario_a_default_startup: ");
    if (!CA_StartupWithContent(&content)) { fprintf(stderr, "FAIL (%s)\n", CA_Error()); return 1; }
    if (CA_ResourceName(LEGACY_RESOURCE_VSWAP) == NULL) FAIL_MSG("VSWAP resource name unresolved");
    CHECK(VL_SetPalette(gamepal, sizeof(gamepal)));
    CHECK(CA_CacheScreen(TITLEPIC));
    CHECK(grsizes[TITLEPIC] == VL_PIXELS);
    CHECK(CA_CacheGrChunk(TITLEPIC));
    /* The decoded screen buffer must contain the synthetic title picture:
       framebuffer[row * W3R_SCREEN_WIDTH + col * 4 + plane] holds
       picture[row * W3R_SCREEN_WIDTH + plane + 4 * col]. */
    {
        const w3r_byte *src = grsegs[TITLEPIC];
        const size_t plane_size = ((size_t)W3R_SCREEN_WIDTH / 4) * (size_t)W3R_SCREEN_HEIGHT;
        for (size_t row = 0; row < (size_t)W3R_SCREEN_HEIGHT; ++row) {
            for (unsigned plane = 0; plane < 4; ++plane) {
                for (unsigned col = 0; col < (unsigned)((size_t)W3R_SCREEN_WIDTH / 4); ++col) {
                    size_t fidx = row * (size_t)W3R_SCREEN_WIDTH + (size_t)col * 4 + plane;
                    unsigned expected = (unsigned)(((plane + 4u * col) * 13u + (unsigned)row * 7u) % 256u);
                    if (framebuffer[fidx] != src[plane * plane_size + row * ((size_t)W3R_SCREEN_WIDTH / 4) + col])
                        FAIL_MSG("framebuffer does not match decoded graphics buffer");
                    if (framebuffer[fidx] != expected) FAIL_MSG("framebuffer content mismatch");
                }
            }
        }
    }
    {
        static w3r_byte rgba[VL_PIXELS * 4];
        CHECK(VL_ConvertRGBA(rgba, sizeof(rgba)));
        for (size_t i = 0; i < VL_PIXELS; ++i) {
            for (unsigned k = 0; k < 3; ++k) {
                unsigned dac = gamepal[framebuffer[i] * 3 + k];
                if (rgba[(i * 4) + k] != (dac * 4 + dac / 16)) {
                    fprintf(stderr, "FAIL pixel mismatch i=%zu k=%u got=%u want=%u\n", i, k, rgba[(i * 4) + k], dac * 4 + dac / 16);
                    return 1;
                }
            }
            if (rgba[(i * 4) + 3] != 255) { fprintf(stderr, "FAIL alpha mismatch i=%zu\n", i); return 1; }
        }
    }
    fprintf(stderr, "graphics pixel content verified\n");
    CA_Shutdown();
    fprintf(stderr, "PASS\n");
    return 0;
}

static int ScenarioRenamedStartupAndGraphics(const char *dir)
{
    legacy_content_t content;
    legacy_content_error_t err = LegacyContent_Init(&content, dir);
    if (err != LEGACY_CONTENT_OK) FAIL_MSG("LegacyContent_Init failed");
    if (LegacyContent_SetResource(&content, LEGACY_RESOURCE_VGADICT, "GFXDICT.WL6") != LEGACY_CONTENT_OK) FAIL_MSG("set VGADICT");
    if (LegacyContent_SetResource(&content, LEGACY_RESOURCE_VGAHEAD, "GFXHEAD.WL6") != LEGACY_CONTENT_OK) FAIL_MSG("set VGAHEAD");
    if (LegacyContent_SetResource(&content, LEGACY_RESOURCE_VGAGRAPH, "GFXGRAPH.WL6") != LEGACY_CONTENT_OK) FAIL_MSG("set VGAGRAPH");
    fprintf(stderr, "scenario_b_renamed_startup: ");
    if (!CA_StartupWithContent(&content)) { fprintf(stderr, "FAIL (%s)\n", CA_Error()); return 1; }
    if (strcmp(CA_ResourceName(LEGACY_RESOURCE_VGADICT), "GFXDICT.WL6") != 0) FAIL_MSG("active VGADICT name");
    if (strcmp(CA_ResourceName(LEGACY_RESOURCE_VGAHEAD), "GFXHEAD.WL6") != 0) FAIL_MSG("active VGAHEAD name");
    if (strcmp(CA_ResourceName(LEGACY_RESOURCE_VGAGRAPH), "GFXGRAPH.WL6") != 0) FAIL_MSG("active VGAGRAPH name");
    CHECK(VL_SetPalette(gamepal, sizeof(gamepal)));
    CHECK(CA_CacheScreen(TITLEPIC));
    CHECK(grsizes[TITLEPIC] == VL_PIXELS);
    CA_Shutdown();
    fprintf(stderr, "PASS\n");
    return 0;
}

static int ScenarioDefaultStartupRejectsRenamed(const char *renamed_dir, const char *original_dir)
{
    fprintf(stderr, "scenario_c_default_startup_rejects_renamed: ");
    if (CA_Startup(renamed_dir)) { fprintf(stderr, "FAIL: default startup unexpectedly succeeded\n"); return 1; }
    if (CA_Error()[0] == '\0') FAIL_MSG("default startup failure reported no error");
    CA_Shutdown();
    /* The failed startup must leave the engine safe to use again. */
    {
        legacy_content_t content;
        if (LegacyContent_Init(&content, original_dir) != LEGACY_CONTENT_OK) FAIL_MSG("LegacyContent_Init after failure");
        if (!CA_StartupWithContent(&content)) { fprintf(stderr, "FAIL (%s)\n", CA_Error()); return 1; }
        CA_Shutdown();
    }
    fprintf(stderr, "PASS\n");
    return 0;
}

static int ScenarioInvalidConfigurations(const char *scratch_dir)
{
    legacy_content_t content;
    legacy_content_error_t err;
    char long_name[80];
    char long_dir[4200];

    fprintf(stderr, "scenario_d_invalid_configurations: ");

    /* NULL descriptor. */
    if (CA_StartupWithContent(NULL)) FAIL_MSG("NULL descriptor accepted");
    /* Empty directory. */
    err = LegacyContent_Init(&content, "");
    if (err != LEGACY_CONTENT_EMPTY_DIRECTORY) FAIL_MSG("empty directory accepted");
    /* Valid directory baseline. */
    err = LegacyContent_Init(&content, "/tmp");
    if (err != LEGACY_CONTENT_OK) FAIL_MSG("valid directory rejected");
    /* Invalid resource identifier. */
    if (LegacyContent_SetResource(&content, (legacy_resource_t)99, "X.WL6") != LEGACY_CONTENT_INVALID_RESOURCE) FAIL_MSG("invalid resource accepted");
    if (LegacyContent_ResourceName(&content, (legacy_resource_t)99) != NULL) FAIL_MSG("invalid resource name resolved");
    /* Empty filename. */
    if (LegacyContent_SetResource(&content, LEGACY_RESOURCE_VSWAP, "") != LEGACY_CONTENT_EMPTY_FILENAME) FAIL_MSG("empty filename accepted");
    /* Path traversal and subdirectory names. */
    if (LegacyContent_SetResource(&content, LEGACY_RESOURCE_VSWAP, "../VGAGRAPH.WL6") != LEGACY_CONTENT_INVALID_FILENAME) FAIL_MSG("path traversal accepted");
    if (LegacyContent_SetResource(&content, LEGACY_RESOURCE_VSWAP, "sub/VGAGRAPH.WL6") != LEGACY_CONTENT_INVALID_FILENAME) FAIL_MSG("subdirectory filename accepted");
    /* Overlong filename. */
    memset(long_name, 'a', sizeof(long_name) - 1);
    long_name[sizeof(long_name) - 1] = '\0';
    if (strlen(long_name) >= LEGACY_CONTENT_FILENAME_MAX) {
        if (LegacyContent_SetResource(&content, LEGACY_RESOURCE_VSWAP, long_name) != LEGACY_CONTENT_FILENAME_TOO_LONG) FAIL_MSG("overlong filename not rejected");
    } else {
        FAIL_MSG("overlong filename construction failed");
    }
    /* Overlong directory. */
    memset(long_dir, 'a', 4096);
    long_dir[4096] = '\0';
    if (LegacyContent_Init(&content, long_dir) != LEGACY_CONTENT_DIRECTORY_TOO_LONG) FAIL_MSG("overlong directory not rejected");
    err = LegacyContent_Init(&content, "/tmp");
    if (err != LEGACY_CONTENT_OK) FAIL_MSG("valid directory rejected after long-directory check");
    /* Overlong combined path. */
    memset(content.directory, 'a', 4090);
    content.directory[4090] = '\0';
    if (LegacyContent_Validate(&content) != LEGACY_CONTENT_PATH_TOO_LONG) FAIL_MSG("overlong content path not rejected");
    /* Restore a valid descriptor for the asset-level scenarios. */
    err = LegacyContent_Init(&content, scratch_dir);
    if (err != LEGACY_CONTENT_OK) FAIL_MSG("scratch directory rejected");

    /* Missing required resource: every resource present except VGAGRAPH. */
    {
        const char *present[] = { "VSWAP.WL6", "MAPHEAD.WL6", "GAMEMAPS.WL6", "AUDIOHED.WL6", "AUDIOT.WL6",
                                  "VGADICT.WL6", "VGAHEAD.WL6" };
        for (size_t i = 0; i < sizeof(present) / sizeof(present[0]); ++i) {
            char path[4096];
            snprintf(path, sizeof(path), "%s/%s", scratch_dir, present[i]);
            FILE *f = fopen(path, "wb");
            if (!f) FAIL_MSG("cannot write missing-asset fixture");
            if (fwrite("x", 1, 1, f) != (size_t)1) FAIL_MSG("cannot write missing-asset fixture");
            (void)fclose(f);
        }
        legacy_content_error_t verr = LEGACY_CONTENT_OK;
        legacy_resource_t missing = LEGACY_RESOURCE_COUNT;
        verr = LegacyContent_ValidateAssets(&content, &missing);
        if (verr != LEGACY_CONTENT_MISSING_ASSET) FAIL_MSG("missing asset not reported");
        if (missing != LEGACY_RESOURCE_VGAGRAPH) FAIL_MSG("missing resource identifier wrong");
    }

    /* Invalid resource data: VGAGRAPH present but malformed for the graphics loader. */
    {
        char path[4096];
        snprintf(path, sizeof(path), "%s/VGAGRAPH.WL6", scratch_dir);
        FILE *f = fopen(path, "wb");
        if (!f) FAIL_MSG("cannot write invalid-asset fixture");
        if (fwrite("xx", 1, 2, f) != (size_t)2) FAIL_MSG("cannot write invalid-asset fixture");
        (void)fclose(f);
        if (CA_StartupWithContent(&content)) FAIL_MSG("invalid graphics data accepted");
    }

    fprintf(stderr, "PASS\n");
    return 0;
}

static int ScenarioDescriptorOwnership(const char *dir)
{
    legacy_content_t content;
    if (LegacyContent_Init(&content, dir) != LEGACY_CONTENT_OK) FAIL_MSG("LegacyContent_Init failed");
    fprintf(stderr, "scenario_e_descriptor_ownership: ");
    if (!CA_StartupWithContent(&content)) { fprintf(stderr, "FAIL (%s)\n", CA_Error()); return 1; }
    if (LegacyContent_SetResource(&content, LEGACY_RESOURCE_VSWAP, "CALLER_OWNS_ME.WL6") != LEGACY_CONTENT_OK) FAIL_MSG("caller descriptor mutation rejected");
    if (strcmp(CA_ResourceName(LEGACY_RESOURCE_VSWAP), "VSWAP.WL6") != 0) FAIL_MSG("engine active name changed after caller mutation");
    if (strcmp(CA_ResourceName(LEGACY_RESOURCE_GAMEMAPS), "GAMEMAPS.WL6") != 0) FAIL_MSG("engine active map name changed after caller mutation");
    CA_Shutdown();
    if (strcmp(CA_ResourceName(LEGACY_RESOURCE_VSWAP), "VSWAP.WL6") != 0) FAIL_MSG("default not restored after shutdown");
    fprintf(stderr, "PASS\n");
    return 0;
}

static int ScenarioRestart(const char *original_dir, const char *renamed_dir)
{
    legacy_content_t content;
    fprintf(stderr, "scenario_f_restart: ");
    if (LegacyContent_Init(&content, original_dir) != LEGACY_CONTENT_OK) FAIL_MSG("LegacyContent_Init failed");
    if (!CA_StartupWithContent(&content)) { fprintf(stderr, "FAIL (%s)\n", CA_Error()); return 1; }
    CA_Shutdown();
    if (LegacyContent_Init(&content, renamed_dir) != LEGACY_CONTENT_OK) FAIL_MSG("LegacyContent_Init failed");
    if (LegacyContent_SetResource(&content, LEGACY_RESOURCE_VGADICT, "GFXDICT.WL6") != LEGACY_CONTENT_OK) FAIL_MSG("set VGADICT");
    if (LegacyContent_SetResource(&content, LEGACY_RESOURCE_VGAHEAD, "GFXHEAD.WL6") != LEGACY_CONTENT_OK) FAIL_MSG("set VGAHEAD");
    if (LegacyContent_SetResource(&content, LEGACY_RESOURCE_VGAGRAPH, "GFXGRAPH.WL6") != LEGACY_CONTENT_OK) FAIL_MSG("set VGAGRAPH");
    if (!CA_StartupWithContent(&content)) { fprintf(stderr, "FAIL (%s)\n", CA_Error()); return 1; }
    if (strcmp(CA_ResourceName(LEGACY_RESOURCE_VGAGRAPH), "GFXGRAPH.WL6") != 0) FAIL_MSG("restart renamed VGAGRAPH name");
    CA_Shutdown();
    fprintf(stderr, "PASS\n");
    return 0;
}

int main(int argc, char **argv)
{
    if (argc != 4) {
        fprintf(stderr, "usage: %s <original_dir> <renamed_dir> <scratch_dir>\n", argv[0]);
        return 2;
    }
    const char *original_dir = argv[1];
    const char *renamed_dir = argv[2];
    const char *scratch_dir = argv[3];

    MM_Startup();

    if (ScenarioOriginalStartupAndGraphics(original_dir)) return 1;
    if (ScenarioRenamedStartupAndGraphics(renamed_dir)) return 1;
    if (ScenarioDefaultStartupRejectsRenamed(renamed_dir, original_dir)) return 1;
    if (ScenarioInvalidConfigurations(scratch_dir)) return 1;
    if (ScenarioDescriptorOwnership(original_dir)) return 1;
    if (ScenarioRestart(original_dir, renamed_dir)) return 1;

    CA_Shutdown();
    MM_Shutdown();
    fprintf(stderr, "=== Legacy content integration tests complete ===\n");
    return 0;
}
